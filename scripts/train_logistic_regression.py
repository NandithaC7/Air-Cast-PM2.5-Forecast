#!/usr/bin/env python3
"""
Standalone AirCast India PySpark MLlib model training script.

Run from the AirCast India project root using the project's Python 3.11
environment and Spark 3.5.9. The script uses the existing engineered dataset,
a chronological 70/15/15 date split, train-only imputation/scaling, validation
threshold selection, and an untouched test set for final metrics.
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

import numpy as np
from pyspark.sql import SparkSession, functions as F
from pyspark.ml import Pipeline, PipelineModel
from pyspark.ml.feature import Imputer, VectorAssembler, StandardScaler
from pyspark.ml.classification import LogisticRegression

ROOT = Path(__file__).resolve().parents[2]
FEATURE_DIR = ROOT / "preprocessed" / "expanded" / "model_features"
OUT_DIR = ROOT / "outputs" / "ml_models" / 'logistic_regression'
MODEL_DIR = ROOT / "models" / 'logistic_regression'

# Numeric predictors already created by the AirCast feature-engineering step.
FEATURES = [
    "valid_reading_count", "daily_mean_pm25", "daily_min_pm25",
    "daily_max_pm25", "pm25_lag1", "pm25_lag2", "pm25_lag3",
    "pm25_roll7", "pm25_delta1", "month_sin", "month_cos",
    "is_winter", "dow",
]
LABEL = "label"
DATE = "local_date"
SEED = 42


def main() -> None:
    # Use local Spark for a reproducible single-machine project run.
    spark = (
        SparkSession.builder
        .appName("AirCast-" + 'logistic_regression')
        .master(os.environ.get("SPARK_MASTER", "local[2]"))
        .config("spark.sql.session.timeZone", "Asia/Kolkata")
        .config("spark.hadoop.fs.defaultFS", "file:///")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("WARN")

    # Find the single Spark CSV part generated by feature engineering.
    csv_files = sorted(p for p in FEATURE_DIR.glob("*.csv") if p.is_file())
    if not csv_files:
        raise FileNotFoundError(f"No feature CSV found in {FEATURE_DIR}")
    if len(csv_files) > 1:
        raise RuntimeError(f"Expected one feature CSV, found {len(csv_files)}: {csv_files}")

    # Infer source columns, then cast predictors and labels to numeric types.
    df = spark.read.option("header", True).option("inferSchema", True).csv(str(csv_files[0]))
    required = set(FEATURES + [LABEL, DATE])
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Feature dataset is missing columns: {sorted(missing)}")

    df = df.withColumn(DATE, F.to_date(F.col(DATE))).withColumn(LABEL, F.col(LABEL).cast("double"))
    for col in FEATURES:
        df = df.withColumn(col, F.col(col).cast("double"))
    df = df.filter(F.col(DATE).isNotNull() & F.col(LABEL).isin(0.0, 1.0))

    # Split by unique dates to avoid randomly mixing past and future records.
    dates = [r[0] for r in df.select(DATE).distinct().orderBy(DATE).collect()]
    if len(dates) < 10:
        raise ValueError(f"Not enough distinct dates for a chronological split: {len(dates)}")
    train_end = dates[max(0, int(len(dates) * 0.70) - 1)]
    val_end = dates[max(0, int(len(dates) * 0.85) - 1)]
    train = df.filter(F.col(DATE) <= F.lit(train_end))
    val = df.filter((F.col(DATE) > F.lit(train_end)) & (F.col(DATE) <= F.lit(val_end)))
    test = df.filter(F.col(DATE) > F.lit(val_end))

    # Fit imputation only on training data to prevent information leakage.
    imputer = Imputer(strategy="mean", inputCols=FEATURES, outputCols=[f"{c}__imputed" for c in FEATURES])
    assembler = VectorAssembler(inputCols=[f"{c}__imputed" for c in FEATURES], outputCol="features")
    preprocessing = Pipeline(stages=[imputer, assembler]).fit(train)
    train_p, val_p, test_p = (preprocessing.transform(x).cache() for x in (train, val, test))
    train_p.count(); val_p.count(); test_p.count()

    # Build the selected classifier; standardize features for linear models.
    stages = []
    if True:
        stages.append(StandardScaler(inputCol="features", outputCol="scaledFeatures", withMean=True, withStd=True))
        features_col = "scaledFeatures"
    else:
        features_col = "features"
    estimator = LogisticRegression(
        featuresCol=features_col,
        labelCol=LABEL,
        maxIter=100, regParam=0.01, elasticNetParam=0.0, standardization=False, threshold=0.5
    )
    stages.append(estimator)
    model_pipeline = Pipeline(stages=stages)

    start = time.perf_counter()
    model = model_pipeline.fit(train_p)
    train_seconds = time.perf_counter() - start

    # Score validation data and choose a threshold using validation F1 only.
    val_rows = model.transform(val_p).select(LABEL, "rawPrediction", "probability" if True else LABEL).collect()
    def get_score(row):
        if True:
            return float(row["probability"].toArray()[1])
        return float(row["rawPrediction"].toArray()[-1])

    val_y = np.array([int(r[LABEL]) for r in val_rows])
    val_s = np.array([get_score(r) for r in val_rows])
    candidates = np.unique(np.concatenate(([float(np.min(val_s) - 1e-9)], val_s, [float(np.max(val_s) + 1e-9)])))
    best_threshold, best_f1 = 0.0, -1.0
    for threshold in candidates:
        pred = (val_s >= threshold).astype(int)
        tp = int(((val_y == 1) & (pred == 1)).sum())
        fp = int(((val_y == 0) & (pred == 1)).sum())
        fn = int(((val_y == 1) & (pred == 0)).sum())
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        if f1 > best_f1:
            best_threshold, best_f1 = float(threshold), float(f1)

    # Evaluate once on the untouched test set using the validation-selected threshold.
    pred_start = time.perf_counter()
    test_rows = model.transform(test_p).select(LABEL, "rawPrediction", "probability" if True else LABEL).collect()
    predict_seconds = time.perf_counter() - pred_start
    y = np.array([int(r[LABEL]) for r in test_rows])
    scores = np.array([get_score(r) for r in test_rows])
    predictions = (scores >= best_threshold).astype(int)
    tn = int(((y == 0) & (predictions == 0)).sum())
    fp = int(((y == 0) & (predictions == 1)).sum())
    fn = int(((y == 1) & (predictions == 0)).sum())
    tp = int(((y == 1) & (predictions == 1)).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    accuracy = (tn + tp) / len(y) if len(y) else 0.0

    # Save the fitted preprocessing + classifier together for consistent inference.
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    MODEL_DIR.parent.mkdir(parents=True, exist_ok=True)
    # Bundle the training-fitted imputer/assembler with the classifier for raw-row inference.
    from pyspark.ml import PipelineModel
    complete_model = PipelineModel(stages=list(preprocessing.stages) + list(model.stages))
    complete_model.write().overwrite().save(str(MODEL_DIR))
    report = {
        "model": 'logistic_regression',
        "display_name": 'Logistic Regression',
        "dataset": str(csv_files[0].relative_to(ROOT)),
        "rows": {"train": train_p.count(), "validation": val_p.count(), "test": test_p.count()},
        "date_boundaries": {
            "train_end_inclusive": str(train_end),
            "validation_end_inclusive": str(val_end),
            "test_start_exclusive": str(val_end),
        },
        "validation_threshold": best_threshold,
        "threshold_selection": "maximum F1 on validation partition",
        "test_metrics": {
            "accuracy": accuracy, "precision": precision, "recall": recall, "f1": f1,
            "tn": tn, "fp": fp, "fn": fn, "tp": tp, "n": int(len(y)),
        },
        "score_kind": "probability" if True else "decision_function",
        "runtime_seconds": {"train": train_seconds, "test_inference": predict_seconds},
        "model_path": str(MODEL_DIR.relative_to(ROOT)),
        "note": "Metrics are from this run; no values are prefilled or fabricated.",
    }
    (OUT_DIR / "metrics.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))

    train_p.unpersist(); val_p.unpersist(); test_p.unpersist()
    spark.stop()


if __name__ == "__main__":
    main()
